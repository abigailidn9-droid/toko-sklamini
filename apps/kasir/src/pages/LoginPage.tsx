export function LoginPage({
  settings,
  onEnter,
}: {
  settings: StoreSettings;
  onEnter: (pin: string) => Promise<string | null>;
}) {
  const toast = useToast();
  const [pin, setPin] = useState("");
  const [busy, setBusy] = useState(false);
  const [shake, setShake] = useState(false);
  const busyRef = useRef(false);
  const logo = settings.logoDataUrl.trim();
  const name = settings.storeName.trim() || "TOKO SKLAMINI";

  async function submit(current: string) {
    if (current.length !== 6 || busyRef.current) return;
    busyRef.current = true;
    setBusy(true);
    const msg = await onEnter(current);
    busyRef.current = false;
    setBusy(false);
    if (!msg) return;
    toast.show("PIN salah", "error", "Coba lagi.");
    setShake(true);
    window.setTimeout(() => setShake(false), 420);
    setPin("");
  }

  function addDigit(d: string) {
    if (busyRef.current) return;
    setPin((p) => {
      if (p.length >= 6) return p;
      const next = p + d;
      if (next.length === 6) window.setTimeout(() => void submit(next), 40);
      return next;
    });
  }

  useEffect(() => {
    function onKey(e: KeyboardEvent) {
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      if (e.key >= "0" && e.key <= "9") {
        e.preventDefault();
        addDigit(e.key);
        return;
      }
      if (e.key === "Backspace") {
        e.preventDefault();
        setPin((p) => p.slice(0, -1));
        return;
      }
      if (e.key === "Escape") {
        e.preventDefault();
        setPin("");
      }
    }
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, []);

  return (
    <div className="login-screen">
      <aside className="login-hero">
        <div className="login-hero-inner">
          <div className="login-logo-wrap">
            {logo ? <img src={logo} alt="" /> : <span>{name.slice(0, 1)}</span>}
          </div>
          <p className="login-kicker">Selamat datang di</p>
          <h1>{name}</h1>
          <p className="login-lead">
            Masuk dengan PIN untuk membuka kasir. Data tersimpan di komputer ini dan ikut terkirim ke cloud saat jaringan hidup.
          </p>
        </div>
        <SideWaves />
        <BottomWaves />
      </aside>
      <section className="login-panel">
        <div className={`login-card${busy ? " busy" : ""}`}>
          <div className="login-card-head">
            <h2>Masuk kasir</h2>
            <Text tone="secondary">Masukkan PIN 6 digit</Text>
          </div>
          <div className={`login-dots${shake ? " shake" : ""}`}>
            <PinDots length={pin.length} />
          </div>
          <PinPad
            onDigit={addDigit}
            onClear={() => setPin("")}
            onBack={() => setPin((p) => p.slice(0, -1))}
          />
          <p className="login-foot">Gunakan keypad di layar atau keyboard.</p>
        </div>
      </section>
    </div>
  );
}
